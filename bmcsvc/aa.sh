#!/bin/bash
clear

# 1. 先畫出一個固定在右上角的時鐘框
echo -e "\033[1;25H┌──────────────────┐"
echo -e "\033[2;25H│ 🕒 時間:         │"
echo -e "\033[3;25H└──────────────────┘"

# 2. 模擬你在終端機下方做其他事（主程式提示字元）
echo -e "\033[6;1H[伺服器監控中] 請輸入指令: "

# 3. 背景無窮迴圈：每秒偷偷上去更新時間
while true; do
    # 儲存目前你在輸入指令的游標位置
    echo -ne "\033[s"
    
    # 傳送到 (行2, 列35) 的位置（時鐘框框內部）
    echo -ne "\033[2;35H"
    
    # 印出目前時間（用黃色高亮），並重設顏色
    echo -ne "\033[1;33m$(date +%H:%M:%S)\033[0m"
    
    # 瞬間傳送回你原本輸入指令的地方！
    echo -ne "\033[u"
    
    sleep 1
done